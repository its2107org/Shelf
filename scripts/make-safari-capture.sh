#!/bin/bash
# Rebuilds ShareExtension/SafariCapture.js from the shared extraction scripts.
# Safari runs that file on the page Ian is viewing, so subscriber articles are captured as he sees them.
set -e
cd "$(dirname "$0")/.."
{
  echo "// GENERATED by scripts/make-safari-capture.sh from Shared/Resources. Do not edit by hand."
  echo "(function () {"
  cat Shared/Resources/Readability.js
  echo ";"
  cat Shared/Resources/ShelfExtract.js
  cat <<'JS'
;
window.ExtensionPreprocessingJS = {
  run: function (args) {
    var article = null;
    try { article = shelfExtract(document, document.URL); } catch (e) { article = null; }
    args.completionFunction({ url: document.URL, title: document.title, article: article });
  },
  finalize: function (args) {}
};
})();
var ExtensionPreprocessingJS = window.ExtensionPreprocessingJS;
JS
} > ShareExtension/SafariCapture.js
